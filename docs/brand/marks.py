def wordmark(word, plates, *, advance=15, h=20):
    """Pixel letters with off-register plates behind the keyline copy."""
    width = advance * len(word) - (advance - 11)
    body = []
    for dx, dy, colour in plates:
        for i, ch in enumerate(word):
            for x, y, w, hh in LETTERS[ch]:
                body.append(f'<rect x="{i * advance + x + dx}" y="{y + dy}" '
                            f'width="{w}" height="{hh}" fill="{colour}"/>')
    vb_w, vb_h = width + 3, 17
    return (f'<svg viewBox="0 0 {vb_w} {vb_h}" style="height: {h}px; display: block; '
            f'image-rendering: pixelated" shape-rendering="crispEdges" role="img" '
            f'aria-label="{word}">{"".join(body)}</svg>'), vb_w / vb_h
