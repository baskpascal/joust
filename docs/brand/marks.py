"""ASCII pixel maps to run-length SVG rects."""

def rects(art):
    out = []
    for y, row in enumerate(art.strip("\n").split("\n")):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            run = 1
            while x + run < len(row) and row[x + run] == ch:
                run += 1
            out.append((x, y, run, ch))
            x += run
    return out


def size(art):
    rows = art.strip("\n").split("\n")
    return max(len(r) for r in rows), len(rows)


def svg(art, ink, *, scale=None, w=None, style="", label=""):
    cw, ch = size(art)
    body = "".join(
        f'<rect x="{x}" y="{y}" width="{r}" height="1" fill="{ink[c]}"/>'
        for x, y, r, c in rects(art) if ink.get(c)
    )
    px = f"width: {cw * scale}px; height: {ch * scale}px;" if scale else f"width: {w}px;"
    return (f'<svg viewBox="0 0 {cw} {ch}" style="{px} display: block; image-rendering: pixelated;'
            f'{style}" shape-rendering="crispEdges" role="img" aria-label="{label}">{body}</svg>')


